// Generates dist/sw.js after `vite build`, precaching the app shell, built chunks, core geography
// data, and 4K phone textures so the whole game can run offline when installed.
import { createHash } from 'node:crypto'
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const DIST = new URL('../dist', import.meta.url).pathname
const PUBLIC_DATA = new URL('../public/data', import.meta.url).pathname
const PUBLIC_TEXTURES = new URL('../public/textures', import.meta.url).pathname

function assetVersion() {
  const hash = createHash('sha1')
  const walk = (directory, label) => {
    for (const name of readdirSync(directory).sort()) {
      const full = join(directory, name)
      const rel = `${label}/${name}`
      if (statSync(full).isDirectory()) walk(full, rel)
      else hash.update(rel).update(readFileSync(full))
    }
  }
  walk(PUBLIC_DATA, 'public/data')
  walk(PUBLIC_TEXTURES, 'public/textures')
  return hash.digest('hex').slice(0, 10)
}

const version = assetVersion()
const assetsDir = join(DIST, 'assets')
const assetFiles = readdirSync(assetsDir)
  .filter((name) => (name.endsWith('.js') || name.endsWith('.css')) && !name.endsWith('.br'))
  .sort()

const embedded = assetFiles.some(
  (name) => name.endsWith('.js') && readFileSync(join(assetsDir, name), 'utf8').includes(version),
)
if (!embedded) {
  throw new Error(`VITE_ASSET_VERSION (${version}) was not found in dist/assets/*.js`)
}

const shellFiles = [
  '/manifest.webmanifest',
  '/favicon.svg',
  '/icon-192.png',
  '/icon-512.png',
  '/icon-maskable-512.png',
  '/apple-touch-icon.png',
]
for (const path of shellFiles) {
  if (!existsSync(join(DIST, path.slice(1)))) {
    throw new Error(`Missing precache file in dist/: ${path}`)
  }
}

const precache = [
  '/',
  ...shellFiles,
  ...assetFiles.map((name) => `/assets/${name}`),
  `/data/countries.json?v=${version}`,
  `/data/facts.json?v=${version}`,
  `/data/borders.json?v=${version}`,
  `/data/cities.json?v=${version}`,
  `/textures/earth-4k.webp?v=${version}`,
  `/textures/night-4k.webp?v=${version}`,
]

const SW_FORMAT = 'v1'
const cacheId = createHash('sha1')
  .update(SW_FORMAT)
  .update(JSON.stringify(precache))
  .digest('hex')
  .slice(0, 10)
const cacheName = `world-game-${cacheId}`

const swSource = `/* Generated by scripts/build-sw.mjs — do not edit by hand. */
const CACHE_NAME = ${JSON.stringify(cacheName)}
const RUNTIME_CACHE = 'world-game-runtime-v1'
const MAX_RUNTIME_ENTRIES = 250
const PRECACHE_URLS = ${JSON.stringify(precache, null, 2)}
const PRECACHE_SET = new Set(PRECACHE_URLS)
const FALLBACK_EARTH = ${JSON.stringify(`/textures/earth-4k.webp?v=${version}`)}
const FALLBACK_NIGHT = ${JSON.stringify(`/textures/night-4k.webp?v=${version}`)}

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE_NAME).then((cache) => cache.addAll(PRECACHE_URLS)))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((names) =>
        Promise.all(
          names
            .filter((name) => name.startsWith('world-game-') && name !== CACHE_NAME && name !== RUNTIME_CACHE)
            .map((name) => caches.delete(name)),
        ),
      )
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') {
    self.skipWaiting()
  }
})

async function putRuntime(request, response) {
  const cache = await caches.open(RUNTIME_CACHE)
  await cache.put(request, response)
  const keys = await cache.keys()
  while (keys.length > MAX_RUNTIME_ENTRIES) {
    const oldest = keys.shift()
    if (oldest) await cache.delete(oldest)
  }
}

function isRuntimeStatic(pathname) {
  return (
    pathname.startsWith('/flags/') ||
    pathname.startsWith('/data/sub/') ||
    pathname.startsWith('/textures/')
  )
}

self.addEventListener('fetch', (event) => {
  const { request } = event
  if (request.method !== 'GET') return
  const url = new URL(request.url)
  if (url.origin !== self.location.origin) return
  if (
    url.pathname.startsWith('/api/') ||
    url.pathname.startsWith('/ws') ||
    url.pathname.startsWith('/admin/') ||
    url.pathname.startsWith('/health') ||
    url.pathname === '/sw.js'
  ) {
    return
  }

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request).catch(async () => {
        const cache = await caches.open(CACHE_NAME)
        return (await cache.match('/')) || Response.error()
      }),
    )
    return
  }

  const key = url.pathname + url.search
  if (PRECACHE_SET.has(key)) {
    event.respondWith(
      caches.open(CACHE_NAME).then(async (cache) => (await cache.match(key)) || fetch(request)),
    )
    return
  }

  if (isRuntimeStatic(url.pathname)) {
    event.respondWith(
      caches.match(request).then(async (cached) => {
        if (cached) return cached
        try {
          const response = await fetch(request)
          if (response.ok && response.type === 'basic') {
            event.waitUntil(putRuntime(request, response.clone()))
          }
          return response
        } catch (error) {
          if (url.pathname === '/textures/earth.webp') {
            const fallback = await caches.match(FALLBACK_EARTH)
            if (fallback) return fallback
          } else if (url.pathname === '/textures/night.webp') {
            const fallback = await caches.match(FALLBACK_NIGHT)
            if (fallback) return fallback
          }
          throw error
        }
      }),
    )
  }
})
`

writeFileSync(join(DIST, 'sw.js'), swSource)
console.log(`build-sw: ${precache.length} precached URLs → ${cacheName}`)
