import type { LonLat } from './coords'
import { fetchJson, type GeoData } from './facts'
import type { ScoringRegion } from './scoring'

export const CITY_KEY_PREFIX = 'city:'

/** A major non-capital city from Natural Earth populated places. */
export interface City {
  id: string
  name: string
  countryId: string
  at: LonLat
  population: number
  /** 0 (most prominent) … 1 (least prominent) within the curated city list. */
  difficulty: number
}

export interface CitiesFile {
  cities: City[]
}

export function cityKey(cityId: string): string {
  return `${CITY_KEY_PREFIX}${cityId}`
}

export function cityIdFromKey(key: string): string | null {
  return key.startsWith(CITY_KEY_PREFIX) ? key.slice(CITY_KEY_PREFIX.length) : null
}

/** Fast lookups over the major-city list, shared by modes and UI once lazy-loaded. */
export class CityIndex {
  readonly all: readonly City[]
  private readonly byId: Map<string, City>
  private readonly byCountryMap: Map<string, City[]>

  constructor(cities: readonly City[]) {
    this.all = cities
    this.byId = new Map(cities.map((city) => [city.id, city]))
    this.byCountryMap = new Map()
    for (const city of cities) {
      const list = this.byCountryMap.get(city.countryId) ?? []
      list.push(city)
      this.byCountryMap.set(city.countryId, list)
    }
  }

  get(id: string): City | undefined {
    return this.byId.get(id)
  }

  byCountry(countryId: string): readonly City[] {
    return this.byCountryMap.get(countryId) ?? []
  }

  inRegion(geo: GeoData, region: ScoringRegion): readonly City[] {
    if (region === 'World') return this.all
    return this.all.filter((city) => geo.feature(city.countryId).properties.region === region)
  }
}

let cached: Promise<CityIndex> | null = null
let loaded: CityIndex | null = null

/** Returns the city index if it has already been loaded, without triggering a fetch. */
export function peekCities(): CityIndex | null {
  return loaded
}

/** Loads the major cities once (generated by scripts/build-cities.mjs). */
export function loadCities(): Promise<CityIndex> {
  cached ??= fetchJson<CitiesFile>('data/cities.json')
    .then(({ cities }) => {
      loaded = new CityIndex(cities)
      return loaded
    })
    .catch((error) => {
      // Let a later retry try again.
      cached = null
      throw error
    })
  return cached
}
